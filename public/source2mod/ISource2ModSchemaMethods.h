/**
 * @file ISource2ModSchemaMethods.h
 * @brief The SDK's schema helpers, served by the core.
 *
 * The code behind CBaseEntity::Teleport, CCSPlayerController::TakeDamage,
 * CPlayer_ItemServices::GiveNamedItem, the schema offset lookups, the nav
 * areas, ... lives in the core (the SDK's src/impl). A plugin carries only
 * forwarders, generated by tools/schemamethods/generate.py, that call the
 * core's copy through this interface -- so a fix in a helper ships with a
 * core update, and plugins keep running unchanged.
 *
 * What still needs a plugin rebuild: a changed schema class member (its type),
 * a changed helper signature, the header-only templates and inlines.
 *
 * Each function is found by its signature ("CBaseEntity::Teleport(const
 * Vector*,const QAngle*,const Vector*,HookChain)"). A plugin built against a
 * newer SDK than the core gets a warning for a function the core does not
 * have, and the call does nothing (the return value is value-initialised).
 */

#ifndef _INCLUDE_ISOURCE2MOD_SCHEMAMETHODS_H
#define _INCLUDE_ISOURCE2MOD_SCHEMAMETHODS_H

#pragma once

#include <cstddef>
#include <type_traits>

#define SOURCE2MOD_SCHEMAMETHODS_INTERFACE "ISource2ModSchemaMethods001"

struct Source2ModSchemaMethodEntry
{
    const char* key;
    void* function;
};

class ISource2ModSchemaMethods
{
public:
    virtual ~ISource2ModSchemaMethods() = default;

    /// The core's thunk for a function by its signature key; null when this
    /// core does not have it.
    virtual void* Find(const char* key) = 0;

    virtual int GetCount() = 0;
    virtual const char* GetKey(int index) = 0;
};

/// Plugin side: Find() through g_pSource2ModSchemaMethods (src/forward).
/// @p resolved becomes true once the answer is final -- the interface is
/// there, whether or not it has the key (a missing one is warned about then);
/// before SOURCE2MOD_SAVEVARS() it stays false and the caller asks again.
void* Source2ModSchemaMethod(const char* key, bool& resolved);

/// What a forwarder returns when the core does not have the function.
template <typename R>
inline R Source2ModSchemaMissing()
{
    if constexpr (std::is_void_v<R>)
        return;
    else if constexpr (std::is_reference_v<R> || !std::is_default_constructible_v<R>)
    {
        // Zeroed storage: a reference needs something to point at, and a
        // type without a default constructor (CPlayerSlot) has no R{}.
        using T = std::remove_reference_t<R>;
        alignas(T) static unsigned char s_storage[sizeof(T)] = {};
        return *reinterpret_cast<T*>(s_storage);
    }
    else
        return R{};
}

#ifdef SOURCE2MOD_CORE
/// The core's instance (src/impl/schema_methods.cpp).
ISource2ModSchemaMethods* Source2ModSchemaMethodsImpl();
#endif

#endif //_INCLUDE_ISOURCE2MOD_SCHEMAMETHODS_H
