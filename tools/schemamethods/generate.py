#!/usr/bin/env python3
"""
Generates the two halves of ISource2ModSchemaMethods from the SDK's own
sources, so a fix in a schema helper ships with a core update alone.

  src/impl/**/*.cpp            the helpers' code (Teleport, GiveNamedItem,
                               the schema offset lookups, ...). Compiled into
                               the core only.
  src/impl/schema_methods.gen.cpp
                               the core's half: one thunk per function and the
                               table ISource2ModSchemaMethods::Find() serves,
                               keyed by the function's signature.
  src/forward/schema_forwarders.gen.cpp
                               the plugins' half: every function defined again,
                               as a call through the core's thunk. Compiled
                               into plugins only.

Every non-static function defined at file scope in src/impl is forwarded:
members (`Class::Method`), static members (found as `static` in the class's
header), namespace and free functions. A changed signature is a new key, so a
plugin built against it on an older core gets a warning and a no-op instead of
a call through the wrong type.

    python3 tools/schemamethods/generate.py          write both files
    python3 tools/schemamethods/generate.py --check  exit 1 when they are stale
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
IMPL = os.path.join(ROOT, 'src', 'impl')
PUBLIC = os.path.join(ROOT, 'public')
OUT_CORE = os.path.join(IMPL, 'schema_methods.gen.cpp')
OUT_PLUGIN = os.path.join(ROOT, 'src', 'forward', 'schema_forwarders.gen.cpp')

HEADER = '''// Generated by tools/schemamethods/generate.py from src/impl -- do not edit.
// Run the generator after changing a function there.
'''


# ---------------------------------------------------------------- source scanning

def strip_code(src):
    """Comments and preprocessor lines blanked, string / char literal contents
    blanked; line structure kept."""
    out = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith('//', i):
            j = src.find('\n', i)
            j = n if j < 0 else j
            out.append(' ' * (j - i))
            i = j
        elif src.startswith('/*', i):
            j = src.find('*/', i + 2)
            j = n if j < 0 else j + 2
            out.append(re.sub(r'[^\n]', ' ', src[i:j]))
            i = j
        elif c in '"\'':
            j = i + 1
            while j < n and src[j] != c:
                j += 2 if src[j] == '\\' else 1
            out.append(c + ' ' * (j - i - 1) + c)
            i = j + 1
        else:
            out.append(c)
            i += 1
    text = ''.join(out)
    return '\n'.join('' if l.lstrip().startswith('#') else l for l in text.split('\n'))


def match_close(text, i, open_c, close_c):
    depth = 0
    for j in range(i, len(text)):
        if text[j] == open_c:
            depth += 1
        elif text[j] == close_c:
            depth -= 1
            if depth == 0:
                return j
    raise ValueError('unbalanced %s' % open_c)


def split_top(text, sep=','):
    parts, depth, cur = [], 0, ''
    for c in text:
        if c in '<([{':
            depth += 1
        elif c in '>)]}':
            depth -= 1
        if c == sep and depth == 0:
            parts.append(cur)
            cur = ''
        else:
            cur += c
    if cur.strip():
        parts.append(cur)
    return [p.strip() for p in parts]


def norm(t):
    t = re.sub(r'\s+', ' ', t.strip())
    t = re.sub(r'\s*([*&,<>()\[\]])\s*', r'\1', t)
    return t


class Func:
    def __init__(self, ret, qual, params, const, path):
        self.ret, self.qual, self.params, self.const, self.path = ret, qual, params, const, path
        self.cls = None
        self.static = False
        self.public = True

    @property
    def name(self):
        return self.qual.split('::')[-1]

    def key(self):
        return '%s(%s)%s' % (self.qual, ','.join(norm(t) for t, _ in self.params), ' const' if self.const else '')


def parse_params(text):
    params = []
    for k, p in enumerate(split_top(text)):
        if p in ('', 'void'):
            continue
        assert '=' not in p, 'a default argument in a definition: ' + p
        m = re.match(r'^(.*?[\w>*&\s])\s*\b([A-Za-z_]\w*)\s*$', p)
        if m and not re.search(r'(^|[\s:<,])(const|unsigned|signed|int|char|bool|float|double|long|short|void)$', p) \
                and m.group(1).strip() not in ('', 'const', 'unsigned', 'signed') and not p.endswith(('*', '&', '>')):
            params.append((m.group(1).strip(), m.group(2)))
        else:
            params.append((p, 'p%d' % k))
    return params


def scan_file(path):
    src = open(path, encoding='utf-8-sig').read()
    text = strip_code(src)
    funcs = []

    def walk(start, end, prefix, anonymous):
        i = start
        head_start = start
        while i < end:
            c = text[i]
            if c == ';':
                head_start = i + 1
            elif c == '{':
                head = text[head_start:i].strip()
                close = match_close(text, i, '{', '}')
                m = re.match(r'^namespace\s*([\w:]*)$', head)
                if m:
                    name = m.group(1)
                    walk(i + 1, close, prefix + ([name] if name else []), anonymous or not name)
                elif not anonymous and '(' in head and not re.match(r'^(static|template|inline|class|struct|enum|union|extern)\b', head) \
                        and not re.search(r'=\s*\[', head):
                    f = parse_head(head, prefix, path)
                    if f:
                        funcs.append(f)
                i = close
                head_start = close + 1
            i += 1

    walk(0, len(text), [], False)
    return funcs, src


def parse_head(head, prefix, path):
    head = re.sub(r'\s+', ' ', head)
    m = re.search(r'([~\w]+(?:::[~\w]+)*)\s*\(', head)
    if not m:
        return None
    qual = m.group(1)
    if 'operator' in qual:
        return None
    ret = head[:m.start()].strip()
    open_p = m.end() - 1
    close_p = match_close(head, open_p, '(', ')')
    after = head[close_p + 1:].strip()
    if after and not re.fullmatch(r'(const)?\s*(noexcept)?', after):
        return None
    parts = qual.split('::')
    if not ret or parts[-1].startswith('~') or (len(parts) >= 2 and parts[-1] == parts[-2]):
        # A plugin builds its objects itself: a constructor (or destructor)
        # has to be in every binary, outside src/impl.
        sys.exit('%s: %s is a constructor / destructor -- keep it outside src/impl (src/sdk)'
                 % (os.path.relpath(path, ROOT), qual))
    if prefix:
        qual = '::'.join(prefix + [qual])
    return Func(ret, qual, parse_params(head[open_p + 1:close_p]), after.startswith('const'), path)


# ---------------------------------------------------------------- headers: which names are classes, which are static

_class_bodies = None


def class_bodies():
    global _class_bodies
    if _class_bodies is None:
        _class_bodies = {}
        for root, _, files in os.walk(PUBLIC):
            for f in files:
                if not f.endswith(('.h', '.hpp')):
                    continue
                text = strip_code(open(os.path.join(root, f), encoding='utf-8-sig', errors='replace').read())
                for m in re.finditer(r'\b(class|struct)\s+(?:alignas\([^)]*\)\s*)?([A-Za-z_]\w*)\b[^;{()]*\{', text):
                    try:
                        close = match_close(text, m.end() - 1, '{', '}')
                    except ValueError:
                        continue
                    # The default access goes in front, so the last specifier
                    # before a declaration is its access.
                    default = 'private:' if m.group(1) == 'class' else 'public:'
                    _class_bodies.setdefault(m.group(2), default + '\n' + text[m.end():close])
    return _class_bodies


def resolve(f):
    parts = f.qual.split('::')
    if len(parts) >= 2 and parts[-2] in class_bodies():
        f.cls = '::'.join(parts[:-1])
        body = class_bodies()[parts[-2]]
        f.static = bool(re.search(r'\bstatic\b[^;{}]*?\b%s\s*\(' % re.escape(parts[-1]), body))
        decl = re.search(r'[\s*&]%s\s*\(' % re.escape(parts[-1]), body)
        if decl:
            access = re.findall(r'\b(public|protected|private)\s*:', body[:decl.start()])
            f.public = not access or access[-1] == 'public'


# ---------------------------------------------------------------- output

def includes(sources):
    seen = []
    for src in sources:
        for m in re.finditer(r'^\s*#\s*include\s+"(source2mod/[^"]+)"', src, re.M):
            if m.group(1) not in seen:
                seen.append(m.group(1))
    return seen


def args(f):
    return ', '.join(('std::move(%s)' % n) if 'std::function' in t else n for t, n in f.params)


def self_type(f):
    return ('const %s*' if f.const else '%s*') % f.cls


def fn_type(f):
    types = ([self_type(f)] if f.cls and not f.static else []) + [t for t, _ in f.params]
    return '%s (*)(%s)' % (f.ret, ', '.join(types))


def core_file(funcs, incs):
    out = [HEADER, '#include "source2mod/ISource2ModSchemaMethods.h"\n']
    out += ['#include "%s"' % i for i in incs]
    out.append('\n#include <utility>\n\nnamespace\n{')
    for k, f in enumerate(funcs):
        params = ', '.join('%s %s' % (t, n) for t, n in f.params)
        if f.cls and not f.static:
            sig = self_type(f) + ' self' + (', ' + params if params else '')
            body = 'self->%s(%s)' % (f.name, args(f))
        else:
            sig = params
            body = '%s(%s)' % (f.qual, args(f))
        out.append('    %s Thunk%d(%s)\n    {\n        return %s;\n    }\n' % (f.ret, k, sig, body))
    out.append('}\n\n// extern: a namespace-scope const would be internal to this file.\nextern const Source2ModSchemaMethodEntry g_Source2ModSchemaMethodTable[] = {')
    for k, f in enumerate(funcs):
        out.append('    { "%s", reinterpret_cast<void*>(&Thunk%d) },' % (f.key(), k))
    out.append('};\n\nextern const size_t g_Source2ModSchemaMethodCount = sizeof(g_Source2ModSchemaMethodTable) / sizeof(g_Source2ModSchemaMethodTable[0]);\n')
    return '\n'.join(out)


def plugin_file(funcs, incs):
    out = [HEADER, '#include "source2mod/ISource2ModSchemaMethods.h"\n']
    out += ['#include "%s"' % i for i in incs]
    out.append('\n#include <utility>\n')
    for f in funcs:
        params = ', '.join('%s %s' % (t, n) for t, n in f.params)
        call_args = (['this'] if f.cls and not f.static else []) + [
            ('std::move(%s)' % n) if 'std::function' in t else n for t, n in f.params]
        out.append('''%s %s(%s)%s
{
    using Fn = %s;
    static Fn s_fn = nullptr;
    static bool s_resolved = false;
    if (!s_resolved)
        s_fn = reinterpret_cast<Fn>(Source2ModSchemaMethod("%s", s_resolved));
    if (!s_fn)
        return Source2ModSchemaMissing<%s>();
    return s_fn(%s);
}
''' % (f.ret, f.qual, params, ' const' if f.const else '', fn_type(f), f.key(), f.ret, ', '.join(call_args)))
    return '\n'.join(out)


def main():
    funcs, sources = [], []
    for root, _, files in os.walk(IMPL):
        for name in sorted(files):
            path = os.path.join(root, name)
            if not name.endswith('.cpp') or path in (OUT_CORE,) or name.startswith('schema_methods'):
                continue
            found, src = scan_file(path)
            funcs += found
            sources.append(src)
    for f in funcs:
        resolve(f)
    # A private / protected member is only called by its class's own code,
    # which is all in the core: no thunk (it could not call it), no forwarder.
    hidden = [f.qual for f in funcs if not f.public]
    funcs = [f for f in funcs if f.public]
    funcs.sort(key=lambda f: f.key())
    keys = [f.key() for f in funcs]
    dup = {k for k in keys if keys.count(k) > 1}
    assert not dup, 'duplicate keys: %s' % dup
    incs = includes(sources)
    outputs = {OUT_CORE: core_file(funcs, incs), OUT_PLUGIN: plugin_file(funcs, incs)}

    stale = [p for p, text in outputs.items() if not os.path.exists(p) or open(p, encoding='utf-8').read() != text]
    if '--check' in sys.argv:
        for p in stale:
            print('stale: ' + os.path.relpath(p, ROOT))
        sys.exit(1 if stale else 0)
    for p, text in outputs.items():
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, 'w', encoding='utf-8', newline='\n').write(text)
    members = sum(1 for f in funcs if f.cls and not f.static)
    statics = sum(1 for f in funcs if f.cls and f.static)
    print('%d functions (%d members, %d static members, %d free/namespace); not public, kept in the core: %s'
          % (len(funcs), members, statics, len(funcs) - members - statics, ', '.join(hidden) or 'none'))


main()
